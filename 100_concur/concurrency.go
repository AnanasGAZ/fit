// 1. Первое сообщение
// Напиши программу, в которой
// анонимная горутина отправляет строку "hello" в канал,
// а main получает и печатает ее.
// func main()
// Результат: Одна строка hello. Программа завершается после получения сообщения.
// Ограничения: Один небуферизированный канал, одна новая горутина, одна
// отправка и одно чтение. Канал не закрывай. Отправка является последним
// действием горутины; main ожидает через чтение канала
func ex1() {
	ch := make(chan string)
	go func() {
		ch <- "hello"
	}()
	fmt.Println(<-ch)
}

