// Напиши программу: горутина печатает "готово",
// затем отправляет true в канал done.
// Main получает сигнал и только после этого печатает "конец".
// func main()
func ex7() {
	PrintDone()
}

// Результат: Ровно две строки в порядке: готово, затем конец.

// Ограничения: Done имеет тип chan bool и не имеет буфера.
// Одна отправка сигнала, одно чтение.
// Сигнал отправляй после печати, затем возвращайся из горутины.
// Канал никто не закрывает;
// ожидание по времени не используй.
func PrintDone() {
	done := make(chan bool)
	go func(ch chan bool) {
		fmt.Println("Готово")
		ch <- true
	}(done)
	ok := <-done
	if ok {
		fmt.Println("Конец")
	}
}

