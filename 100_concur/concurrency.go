// Определи Rectangle и метод SendArea.
// Метод вычисляет площадь и передает ее в канал.
// Из main запусти метод через go и напечатай полученный результат.

// Результат: Для Rectangle{Width: 3, Height: 5}
// программа печатает 15.

// Ограничения: Стороны неотрицательные,
// площадь помещается в int.
// Получатель метода передается по значению.
// Один небуферизированный канал,
// одна отправка последним действием метода,
// одно чтение в main. Канал не закрывай

type Rectangle struct{ Width, Height int }

//«Получатель метода передается по значению»
// это  r Rectangle, не r *Rectangle
// значит передается копия и исходное значение не меняется
func (r Rectangle) SendArea(ch chan int) {
	// r.Height = 10
	ch <- r.Height * r.Width
}
func ex8() {
	ch := make(chan int)
	r := Rectangle{Width: 3, Height: 5}
	go r.SendArea(ch)
	fmt.Println(<-ch)
	// fmt.Println(r.Height)
}

