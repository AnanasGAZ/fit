import "fmt"

// 1. Первое сообщение
// Напиши программу, в которой
// анонимная горутина отправляет строку "hello" в канал,
// а main получает и печатает ее.
// func main()
// Результат: Одна строка hello. Программа завершается после получения сообщения.
// Ограничения: Один небуферизированный канал, одна новая горутина, одна
// отправка и одно чтение. Канал не закрывай. Отправка является последним
// действием горутины; main ожидает через чтение канала
func ex1() {
	ch := make(chan string)
	go func() {
		ch <- "hello"
	}()
	fmt.Println(<-ch)
}

// 2. Обычная функция в горутине
// Реализуй SendNumber и запусти ее через go из main. Передай число и канал
// аргументами. Получи число в main и напечатай его.
// func SendNumber(n int, ch chan int)
// func main()
// Результат: При передаче 42 программа печатает 42 один раз.
// Ограничения: Одна новая горутина отправляет ровно одно значение в
// небуферизированный канал и возвращается. Main читает один раз. Канал никто не
// закрывает; глобальные переменные не используй.
func SendNumber(n int, ch chan int) {
	ch <- n
}
func ex2() {
	ch := make(chan int)
	go SendNumber(42, ch)
	fmt.Println(<-ch)
}

// 3. Результат анонимной функции
// Напиши Double: создай внутри канал и анонимную горутину, которая вычисляет
// удвоенное значение. Передай n параметром горутины и верни полученный из
// канала результат.
// func Double(n int) int
// Результат: Double(7) возвращает 14; Double(-3) возвращает -6.
// Ограничения: Один небуферизированный канал и одна новая горутина. Она
// отправляет один результат последним действием. Канал не закрывай. Удвоенное
// значение помещается в int.
func ex3() {
	fmt.Println(Double(7))  // 14
	fmt.Println(Double(-3)) // -6
}
func Double(n int) int {
	ch := make(chan int)
	go func() {
		ch <- n * 2
	}()
	return <-ch
}

