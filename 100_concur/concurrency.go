// посчитай число рун строки в новой горутине
// и верни результат через канал.
// func RuneCountAsync(s string) int
func ex6() {
	for _, s := range []string{"кот", "Go!", ""} {
		fmt.Printf("RuneCountAsync(%q) = %d\n", s, RuneCountAsync(s))
	}
}

// Результат: Для "кот" верни 3,
// для "Go!" верни 3,
// для пустой строки верни 0.

// Ограничения: Вход содержит корректный UTF-8.
// Используй range по строке или []rune.
// Одна горутина передает один int последним действием.
// Канал небуферизированный, закрывать его не нужно
func RuneCountAsync(s string) int {
	ch := make(chan int)
	go func(s string, ch chan int) {
		r := []rune(s)
		countR := len(r)
		ch <- countR
	}(s, ch)
	return <-ch
}

