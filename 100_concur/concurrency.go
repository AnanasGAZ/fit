// Напиши SumAsync: одна горутина проходит по переданному слайсу,
//  считает сумму
// и отправляет ее вызывающей функции.
// func SumAsync(nums []int) int

// Результат: Для [3, -1, 4] верни 6;
//  для пустого или nil-слайса верни 0.
func ex5() {
	s := []int{3, -1, 4}
	fmt.Printf("Сумма слайса %v, равна: %v", s, SumAsync(s))
}

// Ограничения: Даже для пустого слайса отправь один результат.
// Слайс только читай,
// сумму храни локально в горутине.
// Один небуферизированный канал без закрытия;
// после отправки горутина возвращается.
// Сумма помещается в int
func SumAsync(nums []int) int {
	ch := make(chan int)

	go func(nums []int, ch chan int) {
		sum := 0
		for _, n := range nums {
			sum += n
		}
		ch <- sum
	}(nums, ch)
	return <-ch
}

